//! Embeds the built web UI into the agent binary.
//!
//! The agent must be a single file an operator can scp to a server and run, so
//! the dashboard assets are compiled in rather than installed alongside.
//!
//! If `apps/web/dist` has not been built, the generated table is empty and the
//! agent serves its built-in fallback console instead. That keeps
//! `cargo build` working without a Node toolchain, which matters for
//! contributors touching only the Rust side and for distribution packaging.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

fn main() {
    let manifest_dir =
        PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap_or_else(|_| ".".to_string()));
    let dist = manifest_dir.join("../../apps/web/dist");
    let out_dir = PathBuf::from(std::env::var("OUT_DIR").unwrap_or_else(|_| ".".to_string()));

    println!("cargo:rerun-if-changed={}", dist.display());
    println!("cargo:rerun-if-changed=build.rs");

    let mut entries = Vec::new();
    if dist.is_dir() {
        collect(&dist, &dist, &mut entries);
        entries.sort();
    }

    let mut generated = String::new();
    generated.push_str("// @generated by build.rs - do not edit.\n");
    generated.push_str("pub(crate) static EMBEDDED_UI: &[(&str, &str, &[u8])] = &[\n");
    for (route, path) in &entries {
        // `include_bytes!` keeps the assets in .rodata rather than making the
        // build script emit multi-megabyte string literals.
        let _ = writeln!(
            generated,
            "    ({route:?}, {mime:?}, include_bytes!({path:?})),",
            mime = mime_for(route),
        );
    }
    generated.push_str("];\n");

    let target = out_dir.join("embedded_ui.rs");
    if let Err(error) = std::fs::write(&target, generated) {
        println!(
            "cargo:warning=failed to write {}: {error}",
            target.display()
        );
    }
    if entries.is_empty() {
        println!(
            "cargo:warning=apps/web/dist not found - the agent will serve its fallback console. \
             Run `(cd apps/web && pnpm install && pnpm build)` for the full UI."
        );
    }
}

fn collect(root: &Path, dir: &Path, out: &mut Vec<(String, String)>) {
    let Ok(entries) = std::fs::read_dir(dir) else {
        return;
    };
    for entry in entries.filter_map(Result::ok) {
        let path = entry.path();
        if path.is_dir() {
            collect(root, &path, out);
        } else if let Ok(relative) = path.strip_prefix(root) {
            let route = format!("/{}", relative.to_string_lossy().replace('\\', "/"));
            out.push((route, path.to_string_lossy().to_string()));
        }
    }
}

fn mime_for(route: &str) -> &'static str {
    match route.rsplit_once('.').map(|(_, ext)| ext) {
        Some("html") => "text/html; charset=utf-8",
        Some("js") | Some("mjs") => "text/javascript; charset=utf-8",
        Some("css") => "text/css; charset=utf-8",
        Some("json") => "application/json",
        Some("svg") => "image/svg+xml",
        Some("png") => "image/png",
        Some("webp") => "image/webp",
        Some("ico") => "image/x-icon",
        Some("woff2") => "font/woff2",
        Some("map") => "application/json",
        _ => "application/octet-stream",
    }
}
